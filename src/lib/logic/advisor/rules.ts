export type Merchant = (typeof MERCHANTS)[keyof typeof MERCHANTS];

export type CapPeriod = "daily" | "monthly" | "quarterly" | "annually";
export type CapMetric = "points" | "inr" | "cashback";
export type CapScope = "merchant" | "category" | "card";

// Voucher-lane caps additionally support "purchase_inr": a cap on the voucher
// PURCHASE volume (₹ of vouchers bought per period), as opposed to the reward
// metrics which cap the reward value earned. Supersedes the deprecated
// `voucher_monthly_purchase_limit_inr` (a monthly-only purchase_inr cap).
export type VoucherCapMetric = CapMetric | "purchase_inr";

export interface VoucherCap {
  period: CapPeriod;
  metric: VoucherCapMetric;
  value: number;
  scope: CapScope;
}

export const CAP_PERIODS_PER_YEAR: Record<CapPeriod, number> = {
  daily: 365,
  monthly: 12,
  quarterly: 4,
  annually: 1,
};

export type SharedCapType = "combined" | "standalone";

// Sentinel `merchant` value meaning the shared cap is scoped to the whole card
// (pools across merchants) rather than a specific merchant. Lets a group like
// "10:card:combined" key a card-level pool while keeping the multiplier in play.
export const CARD_LEVEL_CAP = "card" as const;
// Sentinel `merchant` value for a card-TOTAL pool. Pools exactly like
// CARD_LEVEL_CAP, but with one behavioural difference: once the pool's reward cap
// is exhausted, the group's own overflow earns NOTHING (0%) instead of falling
// back to the card base rate. Models cards that earn up to a total monthly cap
// and zero beyond. See `groupFallbackRate`.
export const TOTAL_LEVEL_CAP = "total" as const;
// The pool-identity token in a `SharedCapGroup.merchant` slot. Despite the name
// it may be a real merchant, a category (e.g. "utilities" — pools all spend in
// that category), the `CARD_LEVEL_CAP` sentinel ("card"), or the
// `TOTAL_LEVEL_CAP` sentinel ("total"). It is only ever used as an opaque key,
// so merchants and categories share the slot without colliding.
export type SharedCapMerchant =
  | Merchant
  | Category
  | typeof CARD_LEVEL_CAP
  | typeof TOTAL_LEVEL_CAP;

// A rule's shared cap group. `multiplier`/`merchant` identify the accelerated
// tier (and, for `combined`, derive the pool key shared across rules on a card).
// `merchant` may be a real merchant, a category, the `CARD_LEVEL_CAP` sentinel
// ("card"), the `TOTAL_LEVEL_CAP` sentinel ("total"), or null (any merchant).
// `capType`:
//   - "combined"   — this rule's reward_cap pools with other `combined` rules
//                    sharing the same multiplier/merchant key on the same card.
//   - "standalone" — the cap applies to this rule alone (same as having no
//                    group); multiplier/merchant are display-only.
export interface SharedCapGroup {
  multiplier?: number | null;
  merchant?: SharedCapMerchant | null;
  capType: SharedCapType;
}

export function sharedCapGroupKey(group: SharedCapGroup): string {
  return `${group.multiplier ?? "*"}::${group.merchant ?? "*"}`;
}

// Pool key for a VOUCHER-lane shared group. Namespaced so a voucher pool can
// never merge with a direct-lane pool, even when both use the same group token
// (SmartBuy: direct rules pool a reward cap under "10::smartbuy" while voucher
// rules pool a purchase cap under "voucher::10::smartbuy").
export function voucherPoolKey(group: SharedCapGroup): string {
  return `voucher::${sharedCapGroupKey(group)}`;
}

// A `total` group's spend earns 0% once its cap is exhausted; every other group
// (and groupless spend) falls back to the card base rate. Centralised here so the
// engine's per-category and cross-category fallback paths agree.
export function isTotalCapGroup(
  group: SharedCapGroup | null | undefined,
): boolean {
  return group?.merchant === TOTAL_LEVEL_CAP;
}

export function groupFallbackRate(
  group: SharedCapGroup | null | undefined,
  baseRate: number,
): number {
  return isTotalCapGroup(group) ? 0 : baseRate;
}

// Coerce a stored value (legacy array / single object, or null) into the
// canonical single-object form. Used at DB read sites so existing rows keep
// working: legacy pooled rules had no `capType` and were always shared, so they
// map to "combined"; any legacy `id`/`cap` fields are dropped.
export function toSharedCapGroup(raw: unknown): SharedCapGroup | null {
  const first = Array.isArray(raw) ? raw[0] : raw;
  if (!first || typeof first !== "object") return null;
  const g = first as Partial<SharedCapGroup>;
  return {
    multiplier: g.multiplier ?? null,
    merchant: g.merchant ?? null,
    capType: g.capType === "standalone" ? "standalone" : "combined",
  };
}

const VOUCHER_CAP_METRICS = new Set<string>([
  "points",
  "inr",
  "cashback",
  "purchase_inr",
]);
const CAP_PERIOD_SET = new Set<string>(Object.keys(CAP_PERIODS_PER_YEAR));

// Normalize a rule's stored `caps` into the canonical MockRule shape. The
// deprecated `voucher_monthly_purchase_limit_inr` is folded into an equivalent
// `voucher_cap` (monthly purchase_inr — same ×12 annualization the engine used
// to apply) when no explicit voucher_cap is set, so legacy rows keep working
// byte-identically while the engine only ever sees `voucher_cap`.
export function toRuleCaps(raw: unknown): MockRule["caps"] {
  const c = (raw && typeof raw === "object" ? raw : {}) as Record<
    string,
    unknown
  >;
  let voucher_cap: VoucherCap | null = null;
  const vc = c.voucher_cap as Partial<VoucherCap> | null | undefined;
  if (
    vc &&
    typeof vc === "object" &&
    typeof vc.value === "number" &&
    typeof vc.metric === "string" &&
    VOUCHER_CAP_METRICS.has(vc.metric) &&
    typeof vc.period === "string" &&
    CAP_PERIOD_SET.has(vc.period)
  ) {
    voucher_cap = {
      period: vc.period,
      metric: vc.metric,
      value: vc.value,
      scope: vc.scope ?? "merchant",
    };
  }
  const legacyLimit = c.voucher_monthly_purchase_limit_inr;
  if (!voucher_cap && typeof legacyLimit === "number") {
    voucher_cap = {
      period: "monthly",
      metric: "purchase_inr",
      value: legacyLimit,
      scope: "merchant",
    };
  }
  return {
    reward_cap: (c.reward_cap as MockRule["caps"]["reward_cap"]) ?? null,
    voucher_cap,
    max_voucher_size_inr: (c.max_voucher_size_inr as number | null) ?? null,
    vouchers_per_booking: (c.vouchers_per_booking as number | null) ?? null,
  };
}

function sameCap(
  a: NonNullable<MockRule["caps"]["reward_cap"]> | null | undefined,
  b: NonNullable<MockRule["caps"]["reward_cap"]> | null | undefined,
): boolean {
  if (!a && !b) return true;
  if (!a || !b) return false;
  return a.value === b.value && a.period === b.period && a.metric === b.metric;
}

function sameVoucherCap(
  a: VoucherCap | null | undefined,
  b: VoucherCap | null | undefined,
): boolean {
  if (!a && !b) return true;
  if (!a || !b) return false;
  return a.value === b.value && a.period === b.period && a.metric === b.metric;
}

export function validateSharedCapGroups(rules: MockRule[]): void {
  // Only `combined` rules form a shared pool; the pool budget derives from the
  // members' own reward_cap, so members sharing a pool key must agree on it.
  // `standalone` (and groupless) rules keep a private cap and are skipped.
  const byKey = new Map<string, MockRule[]>();
  for (const r of rules) {
    if (!r.is_active) continue;
    const group = r.shared_cap_group;
    if (!group || group.capType !== "combined") continue;
    const key = `${r.cardId}::${sharedCapGroupKey(group)}`;
    const list = byKey.get(key) ?? [];
    list.push(r);
    byKey.set(key, list);
  }
  for (const [key, members] of byKey) {
    if (members.length <= 1) continue;
    const first = members[0].caps.reward_cap;
    for (const m of members.slice(1)) {
      if (!sameCap(first, m.caps.reward_cap)) {
        throw new Error(
          `Shared cap group "${key}" has inconsistent reward_cap across rules: ${members
            .map((x) => x._id)
            .join(", ")}`,
        );
      }
    }
  }

  // Voucher-lane pass: `combined` voucher groups pool the members' voucher_cap,
  // so each member must carry one and they must agree on it.
  const byVoucherKey = new Map<string, MockRule[]>();
  for (const r of rules) {
    if (!r.is_active) continue;
    const group = r.voucher_shared_cap_group;
    if (!group || group.capType !== "combined") continue;
    const key = `${r.cardId}::${voucherPoolKey(group)}`;
    const list = byVoucherKey.get(key) ?? [];
    list.push(r);
    byVoucherKey.set(key, list);
  }
  for (const [key, members] of byVoucherKey) {
    const missing = members.filter((m) => !m.caps.voucher_cap);
    if (missing.length > 0) {
      throw new Error(
        `Voucher shared cap group "${key}" has members without a voucher_cap: ${missing
          .map((x) => x._id)
          .join(", ")}`,
      );
    }
    if (members.length <= 1) continue;
    const first = members[0].caps.voucher_cap;
    for (const m of members.slice(1)) {
      if (!sameVoucherCap(first, m.caps.voucher_cap)) {
        throw new Error(
          `Voucher shared cap group "${key}" has inconsistent voucher_cap across rules: ${members
            .map((x) => x._id)
            .join(", ")}`,
        );
      }
    }
  }
}

// Spend-tiered direct-swipe rate. Some cards change the accelerated rate at a
// per-period spend threshold (e.g. Education: 3X up to ₹20k/month, 10X beyond).
//   - "marginal": each slice of spend earns its own tier's rate (first ₹20k @
//     3X, the rest @ 10X).
//   - "whole": the highest tier whose threshold the per-period spend reaches
//     applies to ALL the spend (cross ₹20k ⇒ everything earns 10X).
// `tiers` are ascending by `min_spend_per_period_inr`; the first should be 0.
// Thresholds are per-period and annualized exactly like reward caps. A rule with
// no schedule (null) is a plain flat `direct_swipe_percentage` rule.
export type DirectSwipeTierMode = "marginal" | "whole";

export interface DirectSwipeTier {
  min_spend_per_period_inr: number;
  rate: number;
}

export interface DirectSwipeSchedule {
  mode: DirectSwipeTierMode;
  period: CapPeriod;
  tiers: DirectSwipeTier[];
}

export interface MockRule {
  _id: string;
  cardId: string;
  category: Category;
  merchant: Merchant | null;

  reward: {
    direct_swipe_percentage: number;
    // Optional spend-tiered schedule for direct swipe. When set, it overrides
    // `direct_swipe_percentage` (which stays as a single-tier fallback rate).
    direct_swipe_schedule?: DirectSwipeSchedule | null;
    voucher_discount_percentage: number;
    voucher_reward_percentage: number;
    convenience_fee_percentage: number;
  };

  caps: {
    reward_cap: {
      period: CapPeriod;
      metric: CapMetric;
      value: number;
      scope: CapScope;
    } | null;
    // Voucher-lane cap. metric "purchase_inr" caps the voucher purchase volume
    // (₹ bought/period); a reward metric caps the voucher lane's reward value,
    // replacing reward_cap in the voucher lane's budget derivation. null =
    // voucher rewards budget from reward_cap, no purchase-volume cap. The
    // deprecated voucher_monthly_purchase_limit_inr is normalized into this
    // field at DB read (see toRuleCaps).
    voucher_cap: VoucherCap | null;
    max_voucher_size_inr: number | null;
    vouchers_per_booking: number | null;
  };

  shared_cap_group: SharedCapGroup | null;
  // Voucher-lane shared group: pools the members' voucher_cap across rules on
  // the same card, keyed by voucherPoolKey (namespaced so it never merges with
  // a direct-lane pool). Members must agree on voucher_cap (validated). null =
  // the voucher_cap (if any) is private to this rule.
  voucher_shared_cap_group: SharedCapGroup | null;

  fuel_surcharge_applicable: number;
  max_fuel_transaction_limit: number;
  redemption_mode: "online" | "offline" | "both";
  voucher_validity_in_months: number | null;
  gv_coins_percentage: number;

  valid_from: Date;
  valid_until: Date | null;

  partner?: string | null;

  is_active: boolean;
}
